def _marker(name: str, end: bool = False) -> str:
    return f"<!-- generated:{name} {'end' if end else 'start'} -->"


def fill_blocks(text: str, blocks: dict[str, Callable[[], str]]) -> str:
    """Rewrite the text between each pair of ``generated:NAME`` markers.

    Raises:
        ValueError: when a page lacks the markers for one of its blocks.
    """
    for name, make in blocks.items():
        start, end = _marker(name), _marker(name, end=True)
        if start not in text or end not in text:
            raise ValueError(f"missing {start} / {end}")
        head, rest = text.split(start, 1)
        _, tail = rest.split(end, 1)
        text = f"{head}{start}\n\n{make().rstrip()}\n\n{end}{tail}"
    return text


