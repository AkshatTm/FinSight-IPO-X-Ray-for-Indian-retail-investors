EXPERIMENT_ROW = re.compile(r"^\| (E\d+[a-z]?) \| (.+)$")
# Files planned under one name that were written under another (the plan tables keep the names).
RESULT_ALIASES = {
    "eval_results/ladder/rules.json": ["ladder_table.json"],
    "eval_results/ladder/qa_pretrained.json": ["ladder_table.json"],
    "qa_finetuned_seed*.json": ["extractor_metrics-*.json"],
    "eval_results/answers.json": ["e7.json"],
    "eval_results/ladder/bilstm_crf_seed*.json": ["bilstm_metrics-*.json"],
    "eval_results/guard.json": ["guard.json", "guard_clf.json", "guard_compare.json"],
}


def _found(planned: str) -> list[str]:
    names = RESULT_ALIASES.get(planned) or [planned.removeprefix("eval_results/")]
    hits: list[str] = []
    for name in names:
        hits += sorted(Path(p).relative_to(EVAL).as_posix() for p in glob.glob(str(EVAL / name)))
    return hits


def experiments() -> list[dict[str, Any]]:
    """Experiments E1–E24 from the Phase 1 and Phase 2 plan tables, with their result files."""
    out = []
    for rel in ("docs/05_DATA_AND_EVALUATION.md", "docs/phase2/B04_DATA_AND_EVALUATION.md"):
        for line in (ROOT / rel).read_text(encoding="utf-8").splitlines():
            m = EXPERIMENT_ROW.match(line)
            if not m:
                continue
            cells = [c.strip() for c in line.strip("|").split(" | ")]
            planned = re.findall(r"`([^`]+\.json[^`]*)`", cells[-1])
            found = sorted({f for p in planned for f in _found(p)})
            out.append({"id": cells[0], "question": cells[1], "planned": planned, "found": found})
    return out


