def stale() -> list[str]:
    """Pages whose committed text differs from what the generator writes."""
    out = []
    for rel, make in PAGES.items():
        path = ROOT / rel
        if not path.exists() or path.read_text(encoding="utf-8") != make():
            out.append(rel)
    for rel, blocks in BLOCKS.items():
        path = ROOT / rel
        current = path.read_text(encoding="utf-8")
        if fill_blocks(current, blocks) != current:
            out.append(rel)
    return out


def main() -> int:
    if "--check" in sys.argv:
        bad = stale()
        for rel in bad:
            print(f"{rel} is stale: run `uv run poe docs-gen`", file=sys.stderr)
        return 1 if bad else 0
    for rel, make in PAGES.items():
        path = ROOT / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(make(), encoding="utf-8", newline="\n")
        print(f"wrote {rel}")
    for rel, blocks in BLOCKS.items():
        path = ROOT / rel
        path.write_text(
            fill_blocks(path.read_text(encoding="utf-8"), blocks), "utf-8", newline="\n"
        )
        print(f"filled {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
