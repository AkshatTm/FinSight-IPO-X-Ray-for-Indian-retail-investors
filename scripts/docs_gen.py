def _seeds(prefix: str) -> list[dict[str, Any]]:
    return [_load(Path(p).name) for p in sorted(glob.glob(str(EVAL / f"{prefix}-*.json")))]


def _ladder_block(rung: str) -> str:
    table = _load("ladder_table.json")
    rows = [
        f"Gold `{table['gold_version']}`, seeds {', '.join(map(str, table['seeds']))}, "
        "bootstrap over IPOs. NVM = normalised value match.\n\n",
        "| Rung | Split | Full NVM [95 % CI] | Body-only NVM [95 % CI] | n (full / body) |\n",
        "| --- | --- | --- | --- | --- |\n",
    ]
    for key, data in table["ladder"].items():
        for split in ("dev", "test"):
            full, body = data[split]["full"], data[split]["body_only"]
            name = f"**{data['label']}**" if key == rung else data["label"]
            rows.append(
                f"| {name} | {split} | {full['nvm']:.2f} {_ci(full['nvm_ci95'])} | "
                f"{body['nvm']:.2f} {_ci(body['nvm_ci95'])} | {full['n']} / {body['n']} |\n"
            )
    return "".join(rows)


def _ci(pair: list[float]) -> str:
    return f"[{pair[0]:.2f}, {pair[1]:.2f}]"


def _failures_block(rung: str) -> str:
    examples = _load("ladder_table.json")["examples_test"][rung]
    wrong = [
        (field, ex)
        for part in ("full", "body_only")
        for field, items in examples.get(part, {}).items()
        for ex in items
        if not ex["correct"]
    ][:3]
    rows = ["| IPO | Field | Read | Checked value |\n| --- | --- | --- | --- |\n"]
    for field, ex in wrong:
        where = f"`{ex['ipo_id']}`" + (f" p.{ex['page']}" if ex.get("page") else "")
        read = _short(ex["read"]) if ex.get("read") else "(nothing found)"
        rows.append(f"| {where} | `{field}` | {read} | {_short(ex['checked'])} |\n")
    return "".join(rows)


def _short(value: object, limit: int = 120) -> str:
    text = _esc(str(value))
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def _training_block(prefix: str, keys: tuple[str, ...]) -> str:
    runs = _seeds(prefix)
    rows = [
        "| Seed | " + " | ".join(keys) + " | Dev EM | Dev F1 | HasAns F1 | NoAns acc |\n",
        "| --- |" + " --- |" * (len(keys) + 4) + "\n",
    ]
    for r in runs:
        rows.append(
            f"| {r['seed']} | "
            + " | ".join(_fmt(r.get(k)) for k in keys)
            + f" | {r['EM']:.3f} | {r['F1']:.3f} | {r['HasAns_F1']:.3f} | {r['NoAns_acc']:.3f} |\n"
        )
    first = runs[0]
    rows.append(
        f"\nBase: `{first['model']}`. Training examples: {first['n_train']}; dev examples: "
        f"{first['n_dev']} ({first['n_answerable']} answerable). GPUs: {first['n_gpu']} "
        "(Kaggle). Dev scores are on weak labels, not gold.\n"
    )
    if "hyperparameters" in first:
        hp = ", ".join(f"{k} {v}" for k, v in first["hyperparameters"].items())
        rows.append(f"Hyperparameters: {hp}; {first['n_params']:,} parameters.\n")
    return "".join(rows)


def _fmt(value: object) -> str:
    if isinstance(value, float):
        return f"{value:g}"
    return "—" if value is None else str(value)


def _rate(r: dict[str, Any]) -> str:
    return f"{r['hits']}/{r['n']} {_ci(r['wilson_95'])}"


